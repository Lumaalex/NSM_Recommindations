def legacy_code_map():
    """Статическая карта «старый код -> новый»: микротемы + все ID мастер-банка.
    Не зависит от того, применялось ли уже переименование к константам модуля, —
    её можно безопасно пересчитывать (в т.ч. при повторном вызове build() в одном процессе)."""
    mig = {}
    for old in _LEGACY_MICRO_IDS:
        new = rename_micro(old)
        if new != old:
            mig[old] = new
    for old in _LEGACY_PHRASE_IDS:
        new = rename_code(old)
        if new != old:
            mig[old] = new
    return mig


