def validate(data):
    """Проверяет целостность данных: все ссылки в ключах и связях ведут на существующие ID."""
    errors = []
    phrase_ids = {p["id"] for p in data["phrases"]}
    svc_ids = {s["id"] for s in data["service_phrases"]}
    micro_ids = {m["id"] for m in data["microblocks"]}
    block_ids = {b["id"] for b in data["blocks"]}
    ability_ids = {a["id"] for a in data["abilities"]}

    for p in data["phrases"]:
        if p["block"] not in block_ids:
            errors.append(f"{p['id']}: неизвестный блок {p['block']}")
        if p.get("micro") and p["micro"] not in micro_ids:
            errors.append(f"{p['id']}: неизвестный микроблок {p['micro']}")
        if p.get("ability") and p["ability"] not in ability_ids:
            errors.append(f"{p['id']}: неизвестная способность {p['ability']}")
        for k in ("links_goal", "links_meth", "links_rec"):
            for ref in p.get(k, []):
                if ref not in phrase_ids:
                    errors.append(f"{p['id']}: ссылка {ref} ({k}) не найдена")

    for q in data.get("survey_core", []):
        if q.get("micro") and q["micro"] not in micro_ids:
            errors.append(f"{q['id']}: неизвестный микроблок {q['micro']}")
        for ans, key in (q.get("key") or {}).items():
            for ref in key.get("as", []) + key.get("goal", []) + key.get("meth", []) + \
                       key.get("rec", []) + key.get("res", []) + key.get("nxt", []):
                if ref not in phrase_ids:
                    errors.append(f"{q['id']}[{ans}]: ссылка {ref} не найдена")
            for ref in key.get("svc", []):
                if ref not in svc_ids:
                    errors.append(f"{q['id']}[{ans}]: служебная фраза {ref} не найдена")
    for q in data["questionnaire"]:
        if q.get("micro") and q["micro"] not in micro_ids:
            errors.append(f"{q['id']}: неизвестный микроблок {q['micro']}")
        for ans, key in (q.get("key") or {}).items():
            for ref in key.get("as", []) + key.get("goal", []) + key.get("meth", []) + \
                       key.get("rec", []) + key.get("res", []) + key.get("nxt", []):
                if ref not in phrase_ids:
                    errors.append(f"{q['id']}[{ans}]: ссылка {ref} не найдена")
            for ref in key.get("svc", []):
                if ref not in svc_ids:
                    errors.append(f"{q['id']}[{ans}]: служебная фраза {ref} не найдена")
    # --- сферы форка v2 -------------------------------------------------------
    all_sphere_ids = {x["id"] for x in SPHERES_BASE + SPHERES_FEDL + SPHERES_DIR}
    fedl_block_ids = {b["id"] for b in data.get("sens_fedl", [])}
    active_spheres = data.get("spheres", [])
    for sp in active_spheres:
        if sp.get("micro") and sp["micro"] not in micro_ids:
            errors.append(f"{sp['id']}: неизвестный микроблок {sp['micro']}")
        for ref in sp.get("bank_as", []) or []:
            ph = next((p for p in data["phrases"] if p["id"] == ref), None)
            if ph is None:
                errors.append(f"{sp['id']}: пул фраз ссылается на несуществующую фразу {ref}")
            elif ph.get("block") != "AS":
                errors.append(f"{sp['id']}: в пуле сферы должна быть фраза блока AS, а не {ref}")
        for bid in sp.get("sens_blocks", []) or []:
            if bid not in fedl_block_ids:
                errors.append(f"{sp['id']}: неизвестный блок таблицы FEDL2i — {bid}")
        keys = data.get("sphere_keys", {}).get(sp["id"], {})
        for need in (5, 4, 3, 2, 1, "SIG-STRESS", "SIG-NOINFO"):
            if need not in keys:
                errors.append(f"{sp['id']}: нет ключа для оценки {need}")
        if not sp.get("sens_blocks") and not any(keys.get(p, {}).get("as") for p in (5, 4, 3, 2, 1)):
            errors.append(f"{sp['id']}: у сферы нет ни формулировок банка, ни блоков FEDL2i")
    for sid in all_sphere_ids:
        if sid not in data.get("sphere_keys", {}):
            errors.append(f"sphere_keys: нет ключей для сферы {sid}")
    # --- шкала МКФ: критерий через поддержку и соответствие V1 ---------------
    for x in data["ped_scale"]:
        if not str(x.get("support") or "").strip():
            errors.append(f"шкала {x['ped']}: пустой критерий через поддержку (support)")
        if not str(x.get("v1") or "").strip():
            errors.append(f"шкала {x['ped']}: пустое соответствие V1")
    for x in data["ped_signals"]:
        if not str(x.get("v1") or "").strip():
            errors.append(f"сигнал {x['id']}: пустое соответствие V1")
    for sub_list in (data.get("lit_rules") or {}).values():
        for sub in sub_list:
            if not any(sub in t for t in data.get("literature", [])):
                errors.append(f"lit_rules: подстрока «{sub}» не встречается в списке литературы")
    mig = data.get("sphere_migration") or {}
    for old, new in mig.items():
        if new not in all_sphere_ids:
            errors.append(f"sphere_migration: {old} -> неизвестная сфера {new}")

    for sid, keys in data.get("sphere_keys", {}).items():
        if sid not in all_sphere_ids:
            errors.append(f"sphere_keys: неизвестная сфера {sid}")
        for ped, key in keys.items():
            for ref in key.get("as", []) + key.get("goal", []) + key.get("meth", []) + \
                       key.get("rec", []) + key.get("res", []) + key.get("nxt", []):
                if ref not in phrase_ids:
                    errors.append(f"{sid}[{ped}]: ссылка {ref} не найдена")
            for ref in key.get("svc", []):
                if ref not in svc_ids:
                    errors.append(f"{sid}[{ped}]: служебная {ref} не найдена")
    if len(phrase_ids) != len(data["phrases"]):
        errors.append("Есть дублирующиеся ID фраз")
    return errors


