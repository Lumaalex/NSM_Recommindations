# Решение заказчика (2026-09-29, CHANGELOG №45): в кодах микротем вместо «голой» цифры —
# буквенный хвост, чтобы по самому коду было видно, к чему относятся фразы
# (AS1sens = «Актуальное состояние», микротема 1 «Интерес»). Это упрощает будущие обновления банка.
#
# ВАЖНО: в этом файле и в старом Excel-банке коды остаются прежними (AS1-S3-01, AS4, RC1…).
# Переименование выполняется ОДИН РАЗ при сборке (apply_code_rename): JSON, HTML и новый
# Банк_фраз.xlsx получают уже новые коды. Старые сохранённые проекты и старые Excel-банки
# переносятся автоматически — карта переноса лежит в данных (code_migration),
# а при сборке из Excel старые коды переводятся в новые (tools/excel_to_json.py: migrate_legacy).
#
# Хвосты микротем «Актуального состояния» соответствуют сферам оценки форка v2:
#   AS1sens Интерес · AS2emo Эмоции и регуляция · AS3soc Сенсорика · AS4ini Контакт/Инициатива
#   AS5play Игра · AS6com Коммуникация · AS7prax Праксис (v2) · AS8vis Зрительно-пространственная (v2)
# Микротемы рекомендаций:
#   RC1home Общение без требований · RC2int Следование за интересом · RC3sens Сенсорная среда
#   RC4play Поддержка игры · RC5frustr Фрустрация и границы · RC6peers Сверстники
MICRO_SUFFIX = {
    "AS1": "sens", "AS2": "emo", "AS3": "soc", "AS4": "ini",
    "AS5": "play", "AS6": "com", "AS7": "prax", "AS8": "vis",
    "RC1": "home", "RC2": "int", "RC3": "sens", "RC4": "play",
    "RC5": "frustr", "RC6": "peers",
}

_CODE_RE = re.compile(r"^(AS\d|RC\d)(?![A-Za-z])")          # микротема: AS1…, RC1…
_PHRASE_RE = re.compile(r"^(AS\d|RC\d)-(S\d|SN)-([A-Z0-9]+-)?(\d+)$")  # фраза: AS2-FR-S2-01


def rename_micro(code):
    """AS1 -> AS1sens, RC4 -> RC4play. Уже переименованные и неизвестные коды не трогает."""
    if not code:
        return code
    m = _CODE_RE.match(str(code))
    if m and m.group(1) in MICRO_SUFFIX:
        return m.group(1) + MICRO_SUFFIX[m.group(1)] + str(code)[len(m.group(1)):]
    return code


def rename_code(code):
    """AS1-S3-01 -> AS1sens-S3-01; AS2-FR-S2-01 -> AS2emo-FR-S2-01; RC1-… -> RC1home-….
    Преобразование идемпотентно: повторный вызов ничего не меняет."""
    if not code:
        return code
    code = str(code)
    m = _PHRASE_RE.match(code)
    if m and m.group(1) in MICRO_SUFFIX:
        head = m.group(1) + MICRO_SUFFIX[m.group(1)]
        mid = ("-" + m.group(3)[:-1]) if m.group(3) else ""
        return "%s-%s%s-%s" % (head, m.group(2), mid, m.group(4))
    return rename_micro(code)


def _ren_list(lst):
    return [rename_code(x) for x in (lst or [])]


def apply_code_rename(data):
    """Переводит все коды микротем и ID фраз в данных на семантические (см. MICRO_SUFFIX)."""
    for m in data["microblocks"]:
        m["id"] = rename_micro(m["id"])
    for p in data["phrases"]:
        p["id"] = rename_code(p["id"])
        if p.get("micro"):
            p["micro"] = rename_micro(p["micro"])
        for k in ("links_goal", "links_meth", "links_rec"):
            if p.get(k):
                p[k] = _ren_list(p[k])
    for s in data["service_phrases"]:
        if s.get("microblock"):
            s["microblock"] = rename_micro(s["microblock"])
    for a in data["abilities"]:
        if a.get("micro"):
            a["micro"] = rename_micro(a["micro"])
    for q in data.get("questionnaire", []) + data.get("survey_core", []):
        if q.get("micro"):
            q["micro"] = rename_micro(q["micro"])
        for kk in (q.get("key") or {}).values():
            for f in ("as", "goal", "meth", "rec", "res", "nxt"):
                if kk.get(f):
                    kk[f] = _ren_list(kk[f])
    for sp in data.get("spheres", []):
        if sp.get("micro"):
            sp["micro"] = rename_micro(sp["micro"])
        if sp.get("bank_as"):
            sp["bank_as"] = _ren_list(sp["bank_as"])
    for sid, keys in (data.get("sphere_keys") or {}).items():
        for kk in keys.values():
            for f in ("as", "goal", "meth", "rec", "res", "nxt"):
                if kk.get(f):
                    kk[f] = _ren_list(kk[f])


